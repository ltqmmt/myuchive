export function numberName(number: MusicalNumber) {
  return `${number.code ?? number.order}. ${number.title}`
}

/** 막 구분이 있는 공연은 1막/2막으로 묶고, 없으면 한 묶음으로 돌려준다. */
export function groupByAct(list: MusicalNumber[]) {
  const acts = [1, 2] as const
  if (!list.some((n) => n.act)) return [{ act: undefined, numbers: list }]
  return acts.map((act) => ({ act, numbers: list.filter((n) => n.act === act) })).filter((g) => g.numbers.length > 0)
}

export function getShow(showId: string) {
  return shows.find((s) => s.id === showId) ?? shows[0]
}

