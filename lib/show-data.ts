export type MusicalNumber = {
  id: string
  order: number
  /** 막 구분 (1막/2막). 없으면 막 구분 없이 보여준다. */
  act?: 1 | 2
  /** 출처의 넘버 번호(예: 1-8B). 있으면 순번 대신 보여준다. */
  code?: string
  title: string
  scene: string
  /** 넘버 순서와 장면 설명만으로 만든 모의 후기. 북마크한 후기가 없을 때 단서로 보여준다. */
  aiReview: string
}

export type AudienceReview = {
  id: string
  numberId: string
  author: string
  watchedOn: string
  body: string
}

export type Show = {
  id: string
  title: string
  venue: string
  /** 오늘 공연 시간 */
  todayLabel: string
  cast?: string
  numbers: MusicalNumber[]
  reviews: AudienceReview[]
}

